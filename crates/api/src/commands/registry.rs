#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub struct CommandId(&'static str);
impl CommandId {
    pub const fn new(value: &'static str) -> Self {
        Self(value)
    }
    pub const fn as_str(self) -> &'static str {
        self.0
    }
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct CommandMetadata {
    pub id: CommandId,
    pub kind: CommandKind,
    pub capability: &'static str,
    pub action: Action,
    pub input_schema: CommandSchema,
    pub output_schema: CommandSchema,
    pub adapters: &'static [Adapter],
    pub audit_required: bool,
    pub auth_required: bool,
    pub idempotency_required: bool,
    pub timeout_ms: u64,
}

pub struct CommandRegistry;
impl CommandRegistry {
    pub fn all() -> &'static [CommandMetadata] {
        COMMANDS
    }

    pub fn get(id: &str) -> Option<&'static CommandMetadata> {
        COMMANDS.iter().find(|command| command.id.as_str() == id)
    }

    pub const fn source_sha256() -> &'static str {
        COMMAND_REGISTRY_SOURCE_SHA256
    }
}

const fn meta(
    id: &'static str,
    kind: CommandKind,
    capability: &'static str,
    action: Action,
    input_schema: CommandSchema,
    output_schema: CommandSchema,
    adapters: &'static [Adapter],
    audit_required: bool,
    auth_required: bool,
    idempotency_required: bool,
    timeout_ms: u64,
) -> CommandMetadata {
    CommandMetadata {
        id: CommandId::new(id),
        kind,
        capability,
        action,
        input_schema,
        output_schema,
        adapters,
        audit_required,
        auth_required,
        idempotency_required,
        timeout_ms,
    }
}

